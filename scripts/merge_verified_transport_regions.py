#!/usr/bin/env python3
"""Merge verified regional transport extracts without loading the planet in RAM.

Only merges provenance-backed TSV generated by build_verified_transport_links.py.
Each source region can be a Geofabrik extract or independently dated OHM
subset; no region-to-region through route is invented.
"""
import argparse
import csv
import hashlib
import json
import pathlib
import sqlite3

LINK_COLUMNS = ("link_id", "source_feature", "from_province", "to_province", "mode")
SERVICE_COLUMNS = ("service_id", "link_id", "carrier", "from_province",
                   "to_province", "mode", "monthly_capacity", "freight_per_unit",
                   "transit_days", "valid_from_month", "valid_through_month",
                   "source_hash")


def digest(path):
    sha = hashlib.sha256()
    with path.open("rb") as inp:
        for block in iter(lambda: inp.read(4 * 1024 * 1024), b""):
            sha.update(block)
    return sha.hexdigest()


def read_rows(path, columns):
    with path.open("r", encoding="utf-8", newline="") as inp:
        stream = csv.reader(inp, delimiter="\t")
        header = tuple(next(stream, ()))
        if header != columns:
            raise ValueError(f"{path}: transport schema mismatch")
        for line, fields in enumerate(stream, start=2):
            if len(fields) != len(columns) or any(not v for v in fields):
                raise ValueError(f"{path}:{line}: invalid service/link row")
            yield tuple(fields)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("regions", nargs="+", type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    inputs = sorted(set(args.regions), key=lambda p: str(p))
    if not inputs:
        raise ValueError("No source regions")
    db_path = args.output / ".transport-merge.incomplete.db"
    if db_path.exists():
        raise RuntimeError(f"Old uncommitted merge database exists: {db_path}")
    connection = sqlite3.connect(db_path)
    metadata = []
    try:
        connection.execute("CREATE TABLE links "
                           "(id TEXT PRIMARY KEY, origin TEXT, from_id TEXT,"
                           " to_id TEXT, mode TEXT)")
        connection.execute("CREATE TABLE services "
                           "(id TEXT PRIMARY KEY, link_id TEXT, carrier TEXT,"
                           " from_id TEXT, to_id TEXT, mode TEXT, capacity TEXT,"
                           " fare TEXT, days TEXT, first TEXT, last TEXT,"
                           " source_hash TEXT)")
        for region in inputs:
            links_file = region / "geographic_links.tsv"
            services_file = region / "transport_services.tsv"
            provenance_file = region / "provenance.json"
            manifest = json.loads(provenance_file.read_text(encoding="utf-8"))
            if not manifest.get("network_line_data_sha256") or not manifest.get(
                    "province_geodata_sha256"):
                raise ValueError(f"{region}: missing real source hashes")
            manifest["merged_region_path"] = str(region)
            manifest["input_link_sha256"] = digest(links_file)
            manifest["input_service_sha256"] = digest(services_file)
            metadata.append(manifest)
            for row in read_rows(links_file, LINK_COLUMNS):
                existing = connection.execute(
                    "SELECT origin,from_id,to_id,mode FROM links WHERE id=?",
                    (row[0],)).fetchone()
                if existing is not None and existing != row[1:]:
                    raise ValueError(f"Conflicting regional physical link: {row[0]}")
                if existing is None:
                    connection.execute(
                        "INSERT INTO links VALUES(?,?,?,?,?)", row)
            for row in read_rows(services_file, SERVICE_COLUMNS):
                existing = connection.execute(
                    "SELECT link_id,carrier,from_id,to_id,mode,capacity,"
                    "fare,days,first,last,source_hash FROM services WHERE id=?",
                    (row[0],)).fetchone()
                if existing is not None and existing != row[1:]:
                    raise ValueError(f"Conflicting regional route identity: {row[0]}")
                if existing is None:
                    connection.execute(
                        "INSERT INTO services VALUES(?,?,?,?,?,?,?,?,?,?,?,?)",
                        row)
            connection.commit()
        for row in connection.execute(
            "SELECT s.id,s.link_id FROM services s "
            "LEFT JOIN links l ON s.link_id=l.id WHERE l.id IS NULL LIMIT 1"
        ):
            raise ValueError("Service without real physical link: " + row[0])
        for row in connection.execute(
            "SELECT s.id FROM services s JOIN links l ON s.link_id=l.id "
            "WHERE s.from_id!=l.from_id OR s.to_id!=l.to_id "
            "OR s.mode!=l.mode LIMIT 1"
        ):
            raise ValueError("Service disagrees with network link: " + row[0])
        output_links = args.output / "geographic_links.tsv"
        output_services = args.output / "transport_services.tsv"
        for dest, fields, query in (
            (output_links, LINK_COLUMNS,
             "SELECT id,origin,from_id,to_id,mode FROM links ORDER BY id"),
            (output_services, SERVICE_COLUMNS,
             "SELECT * FROM services ORDER BY id"),
        ):
            with dest.open("w", encoding="utf-8", newline="") as out:
                writer = csv.writer(out, delimiter="\t", lineterminator="\n")
                writer.writerow(fields)
                writer.writerows(connection.execute(query))
        link_count = connection.execute("SELECT COUNT(*) FROM links").fetchone()[0]
        route_count = connection.execute(
            "SELECT COUNT(*) FROM services").fetchone()[0]
        (args.output / "merged_provenance.json").write_text(
            json.dumps({
                "source_regions": metadata,
                "unique_physical_links": link_count,
                "unique_independently_verified_services": route_count,
                "service_prices_and_times_never_inferred": True,
                "cross_boundary_routes_not_invented": True,
                "global_link_sha256": digest(output_links),
                "global_service_sha256": digest(output_services),
            }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    finally:
        connection.close()
        db_path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
